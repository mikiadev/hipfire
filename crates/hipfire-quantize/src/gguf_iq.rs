use hipfire_quantize::float16::f16_to_f32;

/// Dequantize Q2_K (ggml type 10, 84 B per 256 elements) to f32.
///
/// Port of `dequantize_row_q2_K` from llama.cpp-escha `ggml/src/ggml-quants.c`.
/// Block layout (note field ORDER: scales first!): `scales[16]`, `qs[64]`,
/// `d` f16, `dmin` f16 (84 B total). Each of the two 128-element halves
/// decodes 4 groups of 32: `dl = d * (scales & 0xF)`,
/// `ml = dmin * (scales >> 4)`, value = `dl * q - ml` with 2-bit q.
pub(crate) fn dequant_q2_k(data: &[u8], n: usize) -> Vec<f32> {
    const QK: usize = 256;
    const BLK: usize = 84;
    let nblocks = n.div_ceil(QK);
    let mut out = vec![0.0f32; n];
    for b in 0..nblocks {
        let base = b * BLK;
        if base + BLK > data.len() {
            break;
        }
        // ggml-common.h block_q2_K: scales[16], qs[64], d, dmin.
        let scales = &data[base..base + 16];
        let qs = &data[base + 16..base + 80];
        let d = f16_to_f32(u16::from_le_bytes([data[base + 80], data[base + 81]]));
        let dmin = f16_to_f32(u16::from_le_bytes([data[base + 82], data[base + 83]]));
        let mut is = 0usize;
        let mut y = b * QK;
        // C: `is` runs 0..16 straight through both halves (NOT reset per
        // half); `q += 32` per half. Scales are consumed in order.
        for half in 0..2 {
            // C: `q += 32` per half — half h reads qs[h*32 .. h*32+32);
            // the four j-groups within a half differ by `shift` (0,2,4,6).
            let q_off = half * 32;
            let mut shift = 0u32;
            for _j in 0..4 {
                let sc = scales[is];
                is += 1;
                let dl = d * (f32::from(sc & 0xF));
                let ml = dmin * (f32::from(sc >> 4));
                for l in 0..16 {
                    let v = ((qs[q_off + l] >> shift) & 3) as i8 as f32;
                    let idx = y + l;
                    if idx < n {
                        out[idx] = dl * v - ml;
                    }
                }
                y += 16;
                let sc = scales[is];
                is += 1;
                let dl = d * (f32::from(sc & 0xF));
                let ml = dmin * (f32::from(sc >> 4));
                for l in 0..16 {
                    let v = ((qs[q_off + 16 + l] >> shift) & 3) as i8 as f32;
                    let idx = y + l;
                    if idx < n {
                        out[idx] = dl * v - ml;
                    }
                }
                y += 16;
                shift += 2;
            }
        }
    }
    out
}

/// Dequantize IQ2_XXS (ggml type 16, 2.0625 bpw, 66 B per 256 elements).
///
/// Port of `dequantize_row_iq2_xxs` from llama.cpp-escha
/// `ggml/src/ggml-quants.c`. Block layout: `d` f16, `qs[64]` (16 x u32
/// pairs packed as bytes). Each 32-element group: `aux32 = qs[2]`,
/// `db = d * (0.5 + (aux32[1] >> 28)) * 0.25`, four grid lookups of
/// `iq2xxs_grid[aux8[l]]` with signs `ksigns_iq2xs[(aux32[1] >> 7*l) & 127]`.
pub(crate) fn dequant_iq2_xxs(data: &[u8], n: usize) -> Vec<f32> {
    const QK: usize = 256;
    const BLK: usize = 66; // 2 + 64
    let nblocks = n.div_ceil(QK);
    let mut out = vec![0.0f32; n];
    for b in 0..nblocks {
        let base = b * BLK;
        if base + BLK > data.len() {
            break;
        }
        let d = f16_to_f32(u16::from_le_bytes([data[base], data[base + 1]]));
        let qs = &data[base + 2..base + 66];
        let mut y = b * QK;
        for ib32 in 0..8 {
            // C: `x[i].qs` is `uint16_t[32]` and the memcpy reads
            // `qs + 4*ib32` ELEMENTS = byte offset 8*ib32 (not 4*ib32).
            let off = 8 * ib32;
            let a0 = u32::from_le_bytes([qs[off], qs[off + 1], qs[off + 2], qs[off + 3]]);
            let a1 = u32::from_le_bytes([qs[off + 4], qs[off + 5], qs[off + 6], qs[off + 7]]);
            // On LE the 8 memcpy'd bytes equal two LE u32s; aux8 spans both.
            let aux8 = [qs[off], qs[off + 1], qs[off + 2], qs[off + 3], qs[off + 4], qs[off + 5], qs[off + 6], qs[off + 7]];
            let db = d * (0.5 + ((a1 >> 28) as f32)) * 0.25;
            for l in 0..4 {
                let grid = IQ2XXS_GRID[aux8[l] as usize];
                let signs = KSIGNS_IQ2XS[((a1 >> (7 * l)) & 127) as usize];
                let gb = grid.to_le_bytes();
                for j in 0..8 {
                    let idx = y + j;
                    if idx < n {
                        out[idx] = db
                            * (gb[j] as i8 as f32)
                            * (if signs & (1u8 << j) != 0 { -1.0 } else { 1.0 });
                    }
                }
                y += 8;
            }
        }
    }
    out
}

/// Dequantize IQ2_XS (ggml type 17, 2.3125 bpw, 74 B per 256 elements).
///
/// Port of `dequantize_row_iq2_xs`. Block layout: `d` f16, `qs[32]` u16
/// (64 B), `scales[8]`. Each 32-element group: `db[2]` from the scales byte
/// (`db = d * (0.5 + nibble) * 0.25`), four lookups `iq2xs_grid[qs & 511]`
/// with signs `ksigns_iq2xs[qs >> 9]`; `db[l/2]` selects the half.
pub(crate) fn dequant_iq2_xs(data: &[u8], n: usize) -> Vec<f32> {
    const QK: usize = 256;
    const BLK: usize = 74; // 2 + 64 + 8
    let nblocks = n.div_ceil(QK);
    let mut out = vec![0.0f32; n];
    for b in 0..nblocks {
        let base = b * BLK;
        if base + BLK > data.len() {
            break;
        }
        let d = f16_to_f32(u16::from_le_bytes([data[base], data[base + 1]]));
        let qs = &data[base + 2..base + 66];
        let scales = &data[base + 66..base + 74];
        let mut y = b * QK;
        for ib32 in 0..8 {
            let sc = scales[ib32];
            let db0 = d * (0.5 + f32::from(sc & 0xf)) * 0.25;
            let db1 = d * (0.5 + f32::from(sc >> 4)) * 0.25;
            for l in 0..4 {
                let q = u16::from_le_bytes([qs[8 * ib32 + 2 * l], qs[8 * ib32 + 2 * l + 1]]);
                let grid = IQ2XS_GRID[(q & 511) as usize];
                let signs = KSIGNS_IQ2XS[(q >> 9) as usize];
                let dl = if l < 2 { db0 } else { db1 };
                let gb = grid.to_le_bytes();
                for j in 0..8 {
                    let idx = y + j;
                    if idx < n {
                        out[idx] = dl
                            * (gb[j] as i8 as f32)
                            * (if signs & (1u8 << j) != 0 { -1.0 } else { 1.0 });
                    }
                }
                y += 8;
            }
        }
    }
    out
}

/// Dequantize IQ2_S (ggml type 22, 2.5625 bpw, 82 B per 256 elements).
///
/// Port of `dequantize_row_iq2_s`. Block layout: `d` f16, `qs[64]`,
/// `qh[8]`, `scales[8]` (signs live at `qs + 32` within the qs region).
/// Each 32-element group: `db[2]` from scales nibbles
/// (`db = d * (0.5 + nibble) * 0.25`), grid
/// `iq2s_grid[qs[l] | (qh[ib32] << (8-2*l) & 0x300)]`, signs `signs[l]`.
pub(crate) fn dequant_iq2_s(data: &[u8], n: usize) -> Vec<f32> {
    const QK: usize = 256;
    const BLK: usize = 82; // 2 + 64 + 8 + 8
    let nblocks = n.div_ceil(QK);
    let mut out = vec![0.0f32; n];
    for b in 0..nblocks {
        let base = b * BLK;
        if base + BLK > data.len() {
            break;
        }
        let d = f16_to_f32(u16::from_le_bytes([data[base], data[base + 1]]));
        let qs = &data[base + 2..base + 66];
        let qh = &data[base + 66..base + 74];
        let scales = &data[base + 74..base + 82];
        // Signs alias the second half of qs (C: `signs = qs + QK_K/8`).
        let signs = &qs[32..64];
        let mut y = b * QK;
        let mut qs_off = 0usize;
        let mut signs_off = 0usize;
        for ib32 in 0..8 {
            let sc = scales[ib32];
            let db0 = d * (0.5 + f32::from(sc & 0xf)) * 0.25;
            let db1 = d * (0.5 + f32::from(sc >> 4)) * 0.25;
            for l in 0..4 {
                let dl = if l < 2 { db0 } else { db1 };
                let grid =
                    IQ2S_GRID[(qs[qs_off + l] as usize | ((qh[ib32] as usize) << (8 - 2 * l)) & 0x300)];
                let s = signs[signs_off + l];
                let gb = grid.to_le_bytes();
                for j in 0..8 {
                    let idx = y + j;
                    if idx < n {
                        out[idx] =
                            dl * (gb[j] as i8 as f32) * (if s & (1u8 << j) != 0 { -1.0 } else { 1.0 });
                    }
                }
                y += 8;
            }
            qs_off += 4;
            signs_off += 4;
        }
    }
    out
}

/// Dequantize IQ3_XXS (ggml type 18, 3.0625 bpw, 98 B per 256 elements).
///
/// Port of `dequantize_row_iq3_xxs`. Block layout: `d` f16, `qs[96]`
/// (first 64 B grid indices, last 32 B packed scale+sign aux u32s).
/// Each 32-element group: `aux32` gives `db = d * (0.5 + (aux32 >> 28)) * 0.5`,
/// grids `iq3xxs_grid[qs]`, signs `ksigns_iq2xs[(aux32 >> 7*l) & 127]`.
/// Grid bytes are u8 codebook values (cast via `as i8`, matching the C's
/// `uint8_t *grid` × float multiply — values ≤ 0x3E fit i8).
pub(crate) fn dequant_iq3_xxs(data: &[u8], n: usize) -> Vec<f32> {
    const QK: usize = 256;
    const BLK: usize = 98; // 2 + 96
    let nblocks = n.div_ceil(QK);
    let mut out = vec![0.0f32; n];
    for b in 0..nblocks {
        let base = b * BLK;
        if base + BLK > data.len() {
            break;
        }
        let d = f16_to_f32(u16::from_le_bytes([data[base], data[base + 1]]));
        let qs = &data[base + 2..base + 66];
        let aux = &data[base + 66..base + 98];
        let mut y = b * QK;
        let mut qs_off = 0usize;
        for ib32 in 0..8 {
            let aux32 = u32::from_le_bytes([
                aux[4 * ib32],
                aux[4 * ib32 + 1],
                aux[4 * ib32 + 2],
                aux[4 * ib32 + 3],
            ]);
            let db = d * (0.5 + ((aux32 >> 28) as f32)) * 0.5;
            for l in 0..4 {
                let signs = KSIGNS_IQ2XS[((aux32 >> (7 * l)) & 127) as usize];
                let g1 = IQ3XXS_GRID[qs[qs_off + 2 * l] as usize];
                let g2 = IQ3XXS_GRID[qs[qs_off + 2 * l + 1] as usize];
                let b1 = g1.to_le_bytes();
                let b2 = g2.to_le_bytes();
                for j in 0..4 {
                    let idx1 = y + j;
                    let idx2 = y + 4 + j;
                    if idx1 < n {
                        out[idx1] = db
                            * (b1[j] as i8 as f32)
                            * (if signs & (1u8 << j) != 0 { -1.0 } else { 1.0 });
                    }
                    if idx2 < n {
                        out[idx2] = db
                            * (b2[j] as i8 as f32)
                            * (if signs & (1u8 << (4 + j)) != 0 { -1.0 } else { 1.0 });
                    }
                }
                y += 8;
            }
            qs_off += 8;
        }
    }
    out
}

/// Dequantize IQ4_XS (ggml type 23, 4.96875 bpw, 136 B per 256 elements).
///
/// Port of `dequantize_row_iq4_xs`. Block layout: `d` f16, `scales_h` u16,
/// `scales_l[4]`, `qs[128]` (nibbles into `kvalues_iq4nl`).
/// Each 32-element group: `ls = (scales_l[ib/2] >> 4*(ib%2) & 0xf)
/// | ((scales_h >> 2*ib) & 3) << 4`, `dl = d * (ls - 32)`,
/// `y = dl * kvalues[qs nibble]`.
pub(crate) fn dequant_iq4_xs(data: &[u8], n: usize) -> Vec<f32> {
    const QK: usize = 256;
    const BLK: usize = 136; // 2 + 2 + 4 + 128
    let nblocks = n.div_ceil(QK);
    let mut out = vec![0.0f32; n];
    for b in 0..nblocks {
        let base = b * BLK;
        if base + BLK > data.len() {
            break;
        }
        let d = f16_to_f32(u16::from_le_bytes([data[base], data[base + 1]]));
        let scales_h = u16::from_le_bytes([data[base + 2], data[base + 3]]);
        let scales_l = &data[base + 4..base + 8];
        let qs = &data[base + 8..base + 136];
        let mut y = b * QK;
        let mut qs_off = 0usize;
        for ib in 0..8 {
            let ls = ((scales_l[ib / 2] >> (4 * (ib % 2))) & 0xf) as i32
                | (((scales_h >> (2 * ib)) & 3) as i32) << 4;
            let dl = d * ((ls - 32) as f32);
            for j in 0..16 {
                let qb = qs[qs_off + j];
                let idx1 = y + j;
                let idx2 = y + 16 + j;
                if idx1 < n {
                    out[idx1] = dl * f32::from(KVALUES_IQ4NL[(qb & 0xf) as usize]);
                }
                if idx2 < n {
                    out[idx2] = dl * f32::from(KVALUES_IQ4NL[(qb >> 4) as usize]);
                }
            }
            y += 32;
            qs_off += 16;
        }
    }
    out
}

/// Dequantize IQ1_M (ggml type 29, 1.75 bpw, 56 B per 256 elements).
///
/// Port of `dequantize_row_iq1_m`. Block layout (NO per-block d):
/// `qs[32]`, `qh[16]`, `scales[8]`. The super-scale `d` is reassembled
/// from nibbles across scales u16s:
/// `scale.u16 = (sc[0] >> 12) | ((sc[1] >> 8) & 0xf0)
/// | ((sc[2] >> 4) & 0xf00) | (sc[3] & 0xf000)`.
/// Each 32-element group uses `dl1/dl2` from 3-bit scale fields and
/// `iq1s_grid` lookups with ±`IQ1M_DELTA` (0.125) shift from qh bits.
pub(crate) fn dequant_iq1_m(data: &[u8], n: usize) -> Vec<f32> {
    const QK: usize = 256;
    const BLK: usize = 56; // 32 + 16 + 8
    const DELTA: f32 = 0.125;
    let nblocks = n.div_ceil(QK);
    let mut out = vec![0.0f32; n];
    for b in 0..nblocks {
        let base = b * BLK;
        if base + BLK > data.len() {
            break;
        }
        let qs = &data[base..base + 32];
        let qh = &data[base + 32..base + 48];
        let sc_bytes = &data[base + 48..base + 56];
        let mut sc = [0u16; 4];
        for i in 0..4 {
            sc[i] = u16::from_le_bytes([sc_bytes[2 * i], sc_bytes[2 * i + 1]]);
        }
        let scale_u16 =
            (sc[0] >> 12) | ((sc[1] >> 8) & 0x00f0) | ((sc[2] >> 4) & 0x0f00) | (sc[3] & 0xf000);
        let d = f16_to_f32(scale_u16);
        let mut y = b * QK;
        let mut qs_off = 0usize;
        let mut qh_off = 0usize;
        for ib in 0..8 {
            let pair = ib / 2;
            let sub = ib % 2;
            let dl1 = d * (f32::from(((sc[pair] >> (6 * sub)) & 0x7) * 2) + 1.0);
            let dl2 = d * (f32::from(((sc[pair] >> (6 * sub + 3)) & 0x7) * 2) + 1.0);
            let idx = [
                qs[qs_off] as usize | (((qh[qh_off] as usize) << 8) & 0x700),
                qs[qs_off + 1] as usize | (((qh[qh_off] as usize) << 4) & 0x700),
                qs[qs_off + 2] as usize | (((qh[qh_off + 1] as usize) << 8) & 0x700),
                qs[qs_off + 3] as usize | (((qh[qh_off + 1] as usize) << 4) & 0x700),
            ];
            let delta = [
                if qh[qh_off] & 0x08 != 0 { -DELTA } else { DELTA },
                if qh[qh_off] & 0x80 != 0 { -DELTA } else { DELTA },
                if qh[qh_off + 1] & 0x08 != 0 { -DELTA } else { DELTA },
                if qh[qh_off + 1] & 0x80 != 0 { -DELTA } else { DELTA },
            ];
            for l in 0..2 {
                let grid = IQ1S_GRID[idx[l]];
                let gb = grid.to_le_bytes();
                for j in 0..8 {
                    let cell = y + j;
                    if cell < n {
                        out[cell] = dl1 * ((gb[j] as i8 as f32) + delta[l]);
                    }
                }
                y += 8;
            }
            for l in 2..4 {
                let grid = IQ1S_GRID[idx[l]];
                let gb = grid.to_le_bytes();
                for j in 0..8 {
                    let cell = y + j;
                    if cell < n {
                        out[cell] = dl2 * ((gb[j] as i8 as f32) + delta[l]);
                    }
                }
                y += 8;
            }
            qs_off += 4;
            qh_off += 2;
        }
    }
    out
}

