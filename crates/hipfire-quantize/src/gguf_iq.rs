    /// IQ1_M's d=0 super-scale likewise yields zeros (no NaN, finite).
    #[test]
    fn zero_blocks_decode_to_zero() {
        assert!(dequant_q2_k(&vec![0u8; 84], 256).iter().all(|&v| v == 0.0));
        assert!(dequant_iq2_xxs(&vec![0u8; 66], 256).iter().all(|&v| v == 0.0));
        assert!(dequant_iq2_xs(&vec![0u8; 74], 256).iter().all(|&v| v == 0.0));
        assert!(dequant_iq2_s(&vec![0u8; 82], 256).iter().all(|&v| v == 0.0));
        assert!(dequant_iq3_xxs(&vec![0u8; 98], 256).iter().all(|&v| v == 0.0));
        assert!(dequant_iq4_xs(&vec![0u8; 136], 256).iter().all(|&v| v == 0.0));
        let z = dequant_iq1_m(&vec![0u8; 56], 256);
        assert!(z.iter().all(|&v| v == 0.0), "first: {:?}", &z[..8]);
    }

    /// d=1.0 smoke on IQ2_XXS: FP16 1.0 in bytes [0,1], rest zero.
    /// aux32[1]=0 → db = 1*(0.5+0)*0.25 = 0.125; grid[0] byte0 = 0x08 = 8;
    /// signs=ksigns[0]=0 (positive). out[0] = 0.125*8 = 1.0.
    #[test]
    fn iq2_xxs_unit_scale_spot() {
        let mut blk = vec![0u8; 66];
        blk[0] = 0x00;
        blk[1] = 0x3C; // FP16 1.0
        let out = dequant_iq2_xxs(&blk, 256);
        assert!((out[0] - 1.0).abs() < 1e-6, "got {}", out[0]);
    }

    /// d=1.0 smoke on IQ4_XS: scales zero → ls=0 → dl = 1*(0-32) = -32;
    /// qs nibble 0 → kvalues[0] = -127. out[0] = -32 * -127 = 4064.
